package com.macys.logistics.shipment.load.exception;

public class PhotoGrabberException extends Exception {
    
    
    /**
     * 
     */
    private static final long serialVersionUID = 1L;
    
    public PhotoGrabberException() {
        super();
    }

    public PhotoGrabberException(String message, Throwable cause) {
        super(message, cause);
    }

    public PhotoGrabberException(String message) {
        super(message);
    }

    public PhotoGrabberException(Throwable cause) {
        super(cause);
    }

}
